"""Build the staff guide.

    python tools/build_staff_guide.py

1. Writes one page per agent to non-technical/staff-guide/agents/<id>.md from each agent.yaml
   (description, who can use it, staff_guide section and conversation starters).
2. Combines the staff guide pages into ready-to-use/Laya-AI-Agents-Staff-Guide.docx (python-docx).

Usually run through build_guides.py, which builds the other Word guides too.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

from paths import CATALOG, ROOT, STAFF_GUIDE as GUIDE, STAFF_GUIDE_DOCX as OUT, STAFF_GUIDE_PAGES as PAGES, TIERS  # noqa: E402


def agent_page(agent: dict, tier: str = "everyone") -> str:
    g = agent["staff_guide"]
    licence = ("**Who can use it:** people with the paid Microsoft Copilot licence."
               if tier == "paid-licence" else "**Who can use it:** everyone, on free Copilot Chat or the paid licence.")
    prompts = "\n".join(f"- *{s['text'].strip()}*" for s in agent["conversation_starters"][:3])
    tips = "\n".join(f"- {t}" for t in g["tips"])
    return f"""# {agent['name']}

{agent['description']}

{licence}

## What to upload

{g['upload']}

## What you get

{g['you_get']}

## Example

{g['example']}

## Try saying

{prompts}

## Tips

{tips}
"""


def write_pages() -> list[Path]:
    PAGES.mkdir(parents=True, exist_ok=True)
    catalog = yaml.safe_load(CATALOG.read_text(encoding="utf-8"))
    paths = []
    for entry in catalog["skills"]:
        aid, tier = entry["agent"], entry["tier"]
        source = TIERS[tier] / "agents" / aid / "agent.yaml"
        agent = yaml.safe_load(source.read_text(encoding="utf-8"))
        path = PAGES / f"{aid}.md"
        path.write_text(
            "<!-- Generated by tools/build_staff_guide.py from %s/agents/%s/agent.yaml - edit that file instead. -->\n\n" % (tier, aid)
            + agent_page(agent, tier),
            encoding="utf-8",
        )
        paths.append(path)
    return paths


# --------------------------------------------------------------------------- markdown -> docx

INLINE = re.compile(r"(\[[^\]]+\]\([^)]+\)|\*\*.+?\*\*|\*[^*\s][^*]*\*|`[^`]+`)")
LINK_PARTS = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")


def add_hyperlink(paragraph, text: str, url: str):
    """A real, clickable link. python-docx has no helper for this, so it's built from the XML."""
    from docx.opc.constants import RELATIONSHIP_TYPE as RT
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn

    rel = paragraph.part.relate_to(url, RT.HYPERLINK, is_external=True)
    link = OxmlElement("w:hyperlink")
    link.set(qn("r:id"), rel)
    run = OxmlElement("w:r")
    props = OxmlElement("w:rPr")
    color = OxmlElement("w:color")
    color.set(qn("w:val"), "0563C1")
    underline = OxmlElement("w:u")
    underline.set(qn("w:val"), "single")
    props.extend([color, underline])
    run.append(props)
    content = OxmlElement("w:t")
    content.text = text
    run.append(content)
    link.append(run)
    paragraph._p.append(link)


def add_inline(paragraph, text: str, bold: bool = False):
    for part in INLINE.split(text):
        if not part:
            continue
        link = LINK_PARTS.fullmatch(part)
        if link:
            label, target = link.groups()
            if target.startswith("http"):
                add_hyperlink(paragraph, label, target)
            else:  # A link to another page in the library means nothing in Word, so keep the words.
                paragraph.add_run(label).bold = bold or None
        elif part.startswith("**") and part.endswith("**") and len(part) > 4:
            add_inline(paragraph, part[2:-2], bold=True)
        elif part.startswith("*") and part.endswith("*") and len(part) > 2:
            paragraph.add_run(part[1:-1]).italic = True
        elif part.startswith("`") and part.endswith("`"):
            run = paragraph.add_run(part[1:-1])
            run.font.name = "Consolas"
            run.bold = bold or None
        else:
            paragraph.add_run(part).bold = bold or None


def render_markdown(doc, text: str):
    lines = [ln for ln in text.splitlines() if not ln.startswith("<!--")]
    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        if not line.strip() or line.strip() == "---":
            i += 1
            continue
        if line.lstrip().startswith("```"):
            i += 1
            while i < len(lines) and not lines[i].lstrip().startswith("```"):
                run = doc.add_paragraph().add_run(lines[i])
                run.font.name = "Consolas"
                i += 1
            i += 1
            continue
        if line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not all(set(c) <= set("-: ") for c in cells):
                    rows.append(cells)
                i += 1
            width = len(rows[0])
            table = doc.add_table(rows=len(rows), cols=width)
            table.style = "Light Grid Accent 1"
            for r, cells in enumerate(rows):
                for c, value in enumerate((cells + [""] * width)[:width]):
                    para = table.cell(r, c).paragraphs[0]
                    add_inline(para, value)
                    if r == 0:
                        for run in para.runs:
                            run.bold = True
            doc.add_paragraph()
            continue
        m = re.match(r"^(#{1,4})\s+(.*)", line)
        if m:
            doc.add_heading(LINK_PARTS.sub(r"\1", m.group(2)), level=len(m.group(1)))
        elif re.match(r"^\s*[-*]\s+", line):
            style = "List Bullet 2" if line.startswith("  ") else "List Bullet"
            item = re.sub(r"^\s*[-*]\s+", "", line).replace("[ ] ", "\u2610 ")
            add_inline(doc.add_paragraph(style=style), item)
        elif re.match(r"^\s*\d+\.\s+", line):
            # Keep the number as text: Word's automatic numbering would run on from the previous list.
            para = doc.add_paragraph(style="List Paragraph")
            add_inline(para, line.strip())
        elif line.startswith(">"):
            add_inline(doc.add_paragraph(style="Intense Quote"), line.lstrip("> "))
        else:
            add_inline(doc.add_paragraph(), line)
        i += 1


def build_docx(pages: list[Path]) -> Path:
    from docx import Document
    from docx.shared import Pt

    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)
    doc.add_heading("Laya AI Agents: Staff Guide", level=0)
    doc.add_paragraph("Your guide to the Laya agents in Microsoft Copilot: what each one does, what to upload, and how to get the best from it.")
    render_markdown(doc, (GUIDE / "getting-started.md").read_text(encoding="utf-8").split("\n", 1)[1])
    for extra in ("which-copilot-do-i-have.md", "when-something-goes-wrong.md"):
        doc.add_page_break()
        render_markdown(doc, (GUIDE / extra).read_text(encoding="utf-8"))
    for page in pages:
        doc.add_page_break()
        render_markdown(doc, page.read_text(encoding="utf-8"))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    return OUT


if __name__ == "__main__":
    pages = write_pages()
    print(f"Wrote {len(pages)} agent pages to {PAGES.relative_to(ROOT)}")
    try:
        print(f"Wrote {build_docx(pages).relative_to(ROOT)}")
    except ImportError:
        print("python-docx is not installed; skipped the Word guide (pip install python-docx).")
        sys.exit(0)
