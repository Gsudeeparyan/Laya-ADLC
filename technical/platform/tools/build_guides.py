"""Build the Word versions of the library, for people who don't read Markdown.

    python tools/build_guides.py

Writes to non-technical/ready-to-use/:
  Laya-AI-Agents-Staff-Guide.docx        how the agents work, and a page on each
  Laya-AI-One-Page-Rules.docx            print it or pin it
  Laya-AI-Basics-Training.docx           AI basics, quiz, team session, champions
  Laya-AI-Playbooks-by-Department.docx   a playbook for each department
  Laya-AI-Prompt-Packs.docx              ready-to-use prompts, free and paid
  Laya-AI-Handbook.docx                  roles, lifecycle and all best practices
and ready-to-use/README.md, saying what's there.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import build_staff_guide  # noqa: E402
from build_staff_guide import render_markdown  # noqa: E402
from paths import BEST_PRACTICES, BY_ROLE, NON_TECHNICAL, PROMPTS, READY, ROLES, TRAINING  # noqa: E402

PLAYBOOK_ORDER = ["member-services", "claims", "sales-and-renewals", "provider-relations", "pricing-and-underwriting",
                  "finance", "hr-and-people", "marketing-and-communications", "compliance-risk-and-legal",
                  "projects-and-operations", "office-and-admin-support", "team-leads-and-managers"]
PAID_PROMPTS = NON_TECHNICAL / "paid-licence" / "prompts"
CARD_ORDER = [
    "every-member-of-staff", "team-lead", "business-owner", "ai-champion", "agent-owner", "library-owner",
    "developer", "tech-lead", "test-engineer", "data-engineer", "platform-engineer", "security-engineer", "service-owner",
    "board-and-senior-management", "ai-owner", "data-protection-officer", "compliance-and-risk", "internal-audit",
    "actuarial-function", "vendor-owner", "platform-admins",
]


def guides() -> dict[str, tuple[str, str, list[Path]]]:
    best = sorted(BEST_PRACTICES.glob("0*.md"))
    return {
        "Laya-AI-One-Page-Rules.docx": ("AI at Laya", "Print it or pin it.", [TRAINING / "one-page-rules.md"]),
        "Laya-AI-Basics-Training.docx": (
            "AI Basics", "For everyone at Laya. No technical background needed.",
            [TRAINING / f for f in ("ai-basics.md", "quiz.md", "one-page-rules.md", "run-a-team-session.md", "being-an-ai-champion.md")]),
        "Laya-AI-Playbooks-by-Department.docx": (
            "AI Playbooks by Department", "What AI can do in your kind of work, what to say, and what stays with you.",
            [BY_ROLE / "README.md"] + [BY_ROLE / f"{slug}.md" for slug in PLAYBOOK_ORDER]),
        "Laya-AI-Prompt-Packs.docx": (
            "AI Prompt Packs", "Ready-to-use prompts for the free version and the paid licence.",
            [PROMPTS / f for f in ("README.md", "everyday-prompts.md", "copilot-chat-in-outlook.md")]
            + [NON_TECHNICAL / "paid-licence" / "README.md"]
            + [PAID_PROMPTS / f"{f}.md" for f in ("word", "excel", "powerpoint", "outlook", "teams", "work-chat")]),
        "Laya-AI-Handbook.docx": (
            "AI at Laya: The Handbook", "Roles, responsibilities and all best practice, in one place.",
            [ROLES / f for f in ("README.md", "risk-tiers.md", "lifecycle.md", "raci.md")]
            + [ROLES / "cards" / f"{slug}.md" for slug in CARD_ORDER]
            + [BEST_PRACTICES / "README.md"] + best + [BEST_PRACTICES / "sources.md"]),
    }


def build_one(title: str, subtitle: str, sources: list[Path], target: Path) -> Path:
    from docx import Document
    from docx.shared import Pt

    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)
    doc.add_heading(title, level=0)
    doc.add_paragraph(subtitle)
    for i, source in enumerate(sources):
        if i:
            doc.add_page_break()
        render_markdown(doc, source.read_text(encoding="utf-8"))
    target.parent.mkdir(parents=True, exist_ok=True)
    doc.save(target)
    return target


def write_index(out: Path) -> None:
    (out / "README.md").write_text("""# Ready to use

Generated by the tools in `technical/platform/tools`. Don't edit these by hand: edit the source and rebuild.

## For all staff: put these on SharePoint

| File | What it is |
|---|---|
| Laya-AI-One-Page-Rules.docx | The rules on one page |
| Laya-AI-Agents-Staff-Guide.docx | How the agents work, which Copilot you have, and what to do when something goes wrong |
| Laya-AI-Basics-Training.docx | AI basics, quiz, team session plan, and the AI champion's guide |
| Laya-AI-Playbooks-by-Department.docx | A playbook for each department |
| Laya-AI-Prompt-Packs.docx | Ready-to-use prompts, for free and paid |
| Laya-AI-Handbook.docx | Roles, responsibilities and all best practice |
| templates/ | AI-safe Excel workbooks and Word templates, including the AI Use Register |

## For IT and agent builders

| Folder | What it is |
|---|---|
| agents/everyone/ | Agents for all staff, on free or paid |
| agents/paid-licence/ | Agents for people with the paid licence |
| agents/README.md | Every agent, and whether it needs anything set up first |

See `non-technical/admin/deploy-agents.md`.
""", encoding="utf-8", newline="\n")


def build_all(out: Path = READY) -> list[Path]:
    built = [build_one(title, subtitle, sources, out / name) for name, (title, subtitle, sources) in guides().items()]
    write_index(out)
    return built


